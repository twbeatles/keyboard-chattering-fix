#[cfg(test)]
mod tests {
    use super::super::language::Language;
    use super::*;

    /// Every newly connected advanced setting must have a visible, non-empty
    /// label in both languages, otherwise the control looks broken.
    #[test]
    fn advanced_settings_have_labels_in_both_languages() {
        for lang in [Language::Ko, Language::En] {
            let s = strings(lang);
            for label in [
                s.min_chatter_label,
                s.min_chatter_unit,
                s.exclude_injected,
                s.log_limit_label,
                s.log_limit_unit,
                s.record_all_keys,
            ] {
                assert!(!label.trim().is_empty(), "empty label for {lang:?}");
            }
        }
    }
}
